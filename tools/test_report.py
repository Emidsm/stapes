#!/usr/bin/env python3
"""Build the test report from test results, and refresh the figures quoted in the README.

Every number comes from the JSON the tests wrote. Nothing here is typed by hand, so the
report cannot drift from what the code does. Values measured by a test and recorded with
`RecordProperty` are listed with the limit they are held to.

Exits non-zero if a test failed or a quoted measurement is missing from the results.
"""

