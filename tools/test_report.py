def recorded_values(results_dir: Path) -> dict[str, str]:
    """Every value a test recorded with RecordProperty, by key."""
    values: dict[str, str] = {}
    for path in sorted(results_dir.glob("*.json")):
        report = json.loads(path.read_text(encoding="utf-8"))
        for suite in report["testsuites"]:
            for test in suite["testsuite"]:
                for key, value in test.items():
                    if key not in RESERVED_KEYS:
                        if key in values:
                            raise ValueError(f"two tests record the same key: {key}")
                        values[key] = str(value)
    return values


def formatted(measurement: Measurement, raw: str) -> str:
    try:
        return f"{float(raw):.{measurement.digits}f} {measurement.unit}".rstrip()
    except ValueError:
        return raw


def build_environment(build_dir: Path | None) -> list[str]:
    """Compiler and build type, read from the build tree that produced the results."""
    if build_dir is None:
        return []
    found = {}
    for path in build_dir.glob("CMakeFiles/*/CMakeCXXCompiler.cmake"):
        text = path.read_text(encoding="utf-8")
        for name in ("CMAKE_CXX_COMPILER_ID", "CMAKE_CXX_COMPILER_VERSION"):
            match = re.search(rf'set\({name} "([^"]*)"\)', text)
            if match:
                found[name] = match.group(1)
    cache = build_dir / "CMakeCache.txt"
    if cache.is_file():
        for name in ("CMAKE_BUILD_TYPE", "CMAKE_SYSTEM_NAME", "CMAKE_HOST_SYSTEM_PROCESSOR"):
            match = re.search(rf"^{name}:\w+=(.*)$", cache.read_text(encoding="utf-8"),
                              re.MULTILINE)
            if match and match.group(1):
                found[name] = match.group(1)
    lines = []
    if "CMAKE_CXX_COMPILER_ID" in found:
        lines.append(f"- Compiler: {found['CMAKE_CXX_COMPILER_ID']} "
                     f"{found.get('CMAKE_CXX_COMPILER_VERSION', '')}".rstrip())
    if "CMAKE_BUILD_TYPE" in found:
        lines.append(f"- Build type: {found['CMAKE_BUILD_TYPE']}")
    return lines


def suite_rows(cases: list[TestCase]) -> list[str]:
    by_binary: dict[str, list[TestCase]] = {}
    for case in cases:
        by_binary.setdefault(case.name.split(":")[0], []).append(case)
    rows = ["| Test binary | Cases | Passed |", "|---|---|---|"]
    for binary, binary_cases in sorted(by_binary.items()):
        passed = sum(case.passed for case in binary_cases)
        rows.append(f"| `{binary}` | {len(binary_cases)} | {passed} |")
    return rows


def area_rows(requirements: dict[str, dict], cases: list[TestCase]) -> list[str]:
    """Requirements grouped by the area in their ID, such as SAF in SRS-SAF-003."""
    areas: dict[str, list[str]] = {}
    for requirement_id in requirements:
        areas.setdefault(requirement_id.split("-")[1], []).append(requirement_id)
    rows = ["| Area | Requirements | Verified | Test cases |", "|---|---|---|---|"]
    for area, ids in areas.items():
        linked = [case for case in cases if any(i in case.requirements for i in ids)]
        verified = sum(
            any(i in case.requirements and case.passed for case in cases) for i in ids)
        rows.append(f"| {area} | {len(ids)} | {verified} | {len(linked)} |")
    return rows


def measurement_rows(values: dict[str, str]) -> tuple[list[str], list[str]]:
    rows = ["| Measurement | Value | Held to |", "|---|---|---|"]
    missing = []
    for measurement in MEASUREMENTS:
        if measurement.key not in values:
            missing.append(measurement.key)
            continue
        rows.append(f"| {measurement.label} | {formatted(measurement, values[measurement.key])} "
                    f"| {measurement.limit} |")
    return rows, missing


def render_report(requirements: dict[str, dict], cases: list[TestCase], values: dict[str, str],
                  environment: list[str]) -> tuple[str, list[str]]:
    passed = sum(case.passed for case in cases)
    rows, missing = measurement_rows(values)
    known = {measurement.key for measurement in MEASUREMENTS}
    others = sorted(key for key in values if key not in known)
    lines = [
        "# Test report",
        "",
        "Generated by `tools/test_report.py` from test results. Do not edit by hand.",
        "",
        f"**{passed} of {len(cases)} test cases passed**, verifying {len(requirements)} "
        "requirements.",
        "",
    ]
    if environment:
        lines += ["## Build", "", *environment, ""]
    lines += ["## Results by test binary", "", *suite_rows(cases), ""]
    lines += ["## Requirements by area", "", *area_rows(requirements, cases), ""]
    lines += [
        "## Measurements",
        "",
        "Values the tests measured on the true state of the simulated robot, which no running",
        "code can see. Each is asserted against the limit beside it, so a passing run means",
        "every row is within its limit.",
        "",
        *rows,
        "",
    ]
    if others:
        lines += ["## Other recorded values", "", "| Key | Value |", "|---|---|"]
        lines += [f"| `{key}` | {values[key]} |" for key in others]
        lines.append("")
    return "\n".join(lines), missing


def render_readme_block(cases: list[TestCase], requirement_count: int, values: dict[str, str],
                        environment: list[str]) -> str:
    passed = sum(case.passed for case in cases)
    lines = [
        README_BEGIN,
        "",
        f"{passed} of {len(cases)} test cases pass, verifying {requirement_count} requirements.",
        "",
        "| Measured on the true state of the simulated robot | Value | Held to |",
        "|---|---|---|",
    ]
    for measurement in MEASUREMENTS:
        if measurement.in_readme and measurement.key in values:
            lines.append(f"| {measurement.label} | {formatted(measurement, values[measurement.key])}"
                         f" | {measurement.limit} |")
    if environment:
        build = ", ".join(line.removeprefix("- ").replace(": ", " ").lower()
                          for line in environment)
        lines += ["", f"Measured with {build}. Results are bit-exact for a given compiler and "
                      "maths library, and differ slightly between them."]
    lines += ["", README_END]
    return "\n".join(lines)


def update_readme(path: Path, block: str) -> None:
    text = path.read_text(encoding="utf-8")
    start = text.find(README_BEGIN)
    end = text.find(README_END)
    if start == -1 or end == -1 or end < start:
        raise ValueError(f"{path} has no evidence markers to fill in")
    path.write_text(text[:start] + block + text[end + len(README_END):], encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--requirements", type=Path, required=True)
    parser.add_argument("--results", type=Path, required=True, help="gtest JSON directory")
    parser.add_argument("--build-dir", type=Path, help="build tree, to report the compiler")
    parser.add_argument("--output", type=Path, help="write the report to this file")
    parser.add_argument("--readme", type=Path,
                        help="refresh the generated block between the markers in this file")
    args = parser.parse_args()

    requirements = load_requirements(args.requirements)
    cases = load_test_cases(args.results)
    values = recorded_values(args.results)
    environment = build_environment(args.build_dir)
    report, missing = render_report(requirements, cases, values, environment)

    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(report, encoding="utf-8")
    if args.readme:
        update_readme(args.readme,
                      render_readme_block(cases, len(requirements), values, environment))

    failed = [case.name for case in cases if not case.passed]
    for name in failed:
        print(f"error: test failed: {name}", file=sys.stderr)
    for key in missing:
        print(f"error: no test recorded the measurement: {key}", file=sys.stderr)
    if not cases:
        print("error: no test results found", file=sys.stderr)
    print(f"{len(cases)} test cases, {len(failed)} failed, {len(missing)} measurements missing")
    return 1 if failed or missing or not cases else 0


if __name__ == "__main__":
    sys.exit(main())
