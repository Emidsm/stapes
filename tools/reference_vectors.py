#!/usr/bin/env python3
"""Print reference values for the generators and the hash in the C++ test suite.

This is an independent implementation of the published algorithms, kept outside the
C++ code on purpose: a value generated by the code under test would prove nothing.
"""

MASK = (1 << 64) - 1


def rotl(value: int, bits: int) -> int:
    return ((value << bits) | (value >> (64 - bits))) & MASK


def splitmix64(seed: int, count: int) -> list[int]:
    outputs = []
    state = seed
    for _ in range(count):
        state = (state + 0x9E3779B97F4A7C15) & MASK
        z = state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK
        outputs.append(z ^ (z >> 31))
    return outputs


def xoshiro256pp(state: list[int], count: int) -> list[int]:
    s = list(state)
    outputs = []
    for _ in range(count):
        outputs.append((rotl((s[0] + s[3]) & MASK, 23) + s[0]) & MASK)
        shifted = (s[1] << 17) & MASK
        s[2] ^= s[0]
        s[3] ^= s[1]
        s[1] ^= s[2]
        s[0] ^= s[3]
        s[2] ^= shifted
        s[3] = rotl(s[3], 45)
    return outputs


def fnv1a64(data: bytes) -> int:
    value = 0xCBF29CE484222325
    for byte in data:
        value = ((value ^ byte) * 0x100000001B3) & MASK
    return value


def main() -> None:
    print("splitmix64(1234567):", splitmix64(1234567, 5))
    print("xoshiro256++(1,2,3,4):", xoshiro256pp([1, 2, 3, 4], 6))
    print(f"fnv1a64(uint64 1, little endian): {fnv1a64((1).to_bytes(8, 'little')):#018x}")


if __name__ == "__main__":
    main()
