#!/usr/bin/env python3
"""Build the traceability matrix from test results, and fail if it has gaps.

Fails when a requirement has no test, a test names an unknown requirement, a linked
test did not pass, or no results were found.
"""

import argparse
import json
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class TestCase:
    name: str
    passed: bool
    requirements: tuple[str, ...]


def load_requirements(path: Path) -> dict[str, dict]:
    with path.open("rb") as file:
        entries = tomllib.load(file)["requirement"]
    requirements: dict[str, dict] = {}
    for entry in entries:
        if entry["id"] in requirements:
            raise ValueError(f"duplicate requirement id: {entry['id']}")
        requirements[entry["id"]] = entry
    return requirements


def load_test_cases(results_dir: Path) -> list[TestCase]:
    cases = []
    for path in sorted(results_dir.glob("*.json")):
        report = json.loads(path.read_text(encoding="utf-8"))
        for suite in report["testsuites"]:
            for test in suite["testsuite"]:
                if test.get("status") == "NOTRUN":
                    continue
                ids = test.get("requirement", "")
                cases.append(
                    TestCase(
                        name=f"{path.stem}: {suite['name']}.{test['name']}",
                        passed="failures" not in test and test.get("result") == "COMPLETED",
                        requirements=tuple(i.strip() for i in ids.split(",") if i.strip()),
                    )
                )
    return cases


def without_layers(requirements: dict[str, dict], skipped: set[str]) -> dict[str, dict]:
    """Drops requirements verified by a layer this build did not run, such as Python."""
    return {requirement_id: requirement for requirement_id, requirement in requirements.items()
            if requirement.get("layer", "core") not in skipped}


def find_problems(requirements: dict[str, dict], cases: list[TestCase]) -> list[str]:
    problems = []
    if not cases:
        problems.append("no test results found")

    linked = {requirement_id: [] for requirement_id in requirements}
    for case in cases:
        if not case.requirements:
            problems.append(f"test declares no requirement: {case.name}")
        for requirement_id in case.requirements:
            if requirement_id not in linked:
                problems.append(f"unknown requirement {requirement_id} in {case.name}")
            else:
                linked[requirement_id].append(case)
        if not case.passed:
            problems.append(f"test failed: {case.name}")

    for requirement_id, requirement_cases in linked.items():
        if not requirement_cases:
            problems.append(f"requirement has no test: {requirement_id}")
    return problems


def render_matrix(requirements: dict[str, dict], cases: list[TestCase]) -> str:
    lines = [
        "# Traceability matrix",
        "",
        "Generated by `tools/traceability.py` from test results. Do not edit by hand.",
        "",
        f"{len(requirements)} requirements, {len(cases)} test cases.",
        "",
        "| Requirement | Statement | Code | Tests | Result |",
        "|---|---|---|---|---|",
    ]
    for requirement_id, requirement in requirements.items():
        linked = [case for case in cases if requirement_id in case.requirements]
        passed = sum(case.passed for case in linked)
        code = "<br>".join(f"`{path}`" for path in requirement["code"])
        tests = "<br>".join(f"`{case.name}`" for case in linked)
        lines.append(
            f"| {requirement_id} | {requirement['statement']} | {code} | {tests} "
            f"| {passed}/{len(linked)} passed |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--requirements", type=Path, required=True)
    parser.add_argument("--results", type=Path, required=True, help="gtest JSON directory")
    parser.add_argument("--output", type=Path, help="write the matrix to this file")
    parser.add_argument("--skip-layer", action="append", default=[],
                        help="leave out requirements of this layer, for a build that does not "
                             "run its tests; the complete matrix needs every layer")
    args = parser.parse_args()

    requirements = without_layers(load_requirements(args.requirements), set(args.skip_layer))
    cases = load_test_cases(args.results)
    problems = find_problems(requirements, cases)

    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(render_matrix(requirements, cases), encoding="utf-8")

    for problem in problems:
        print(f"error: {problem}", file=sys.stderr)
    print(f"{len(requirements)} requirements, {len(cases)} test cases, {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
